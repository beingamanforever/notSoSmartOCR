"""Compare local OCR with deterministic selective visual repair."""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from typing import Any, Callable, Mapping, Sequence

from ocr_pipeline.openrouter import (
    DEFAULT_MAX_TOKENS,
    IMAGE_REPAIR_MODELS,
    MAX_TOKENS,
    repair_image,
)
from ocr_pipeline.pipeline import process_document
from ocr_pipeline.providers import (
    GLMOCRDirectReader,
    GLMOCRReader,
    LocalReader,
    PaddleOCRVLReader,
    TesseractReader,
)
from ocr_pipeline.repair import repair_risky_regions

if __package__:
    from experiments.public_benchmark import (
        NORMALIZATION,
        BenchmarkCase,
        _limit_cases,
        _positive_int,
        _relative_path,
        _score,
        _summarize,
        _transcription_text,
        discover_cases,
        reader_config,
    )
else:
    from public_benchmark import (  # type: ignore[no-redef]
        NORMALIZATION,
        BenchmarkCase,
        _limit_cases,
        _positive_int,
        _relative_path,
        _score,
        _summarize,
        _transcription_text,
        discover_cases,
        reader_config,
    )

RepairCall = Callable[[Path, str, Mapping[str, Any]], Any]
REPAIR_PROTOCOL_VERSION = "different-model-literal-agreement-v2"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Compare local OCR with selective OpenRouter repair"
    )
    parser.add_argument("dataset", choices=("clinocr", "funsd"))
    parser.add_argument("root", type=Path, help="Extracted dataset root")
    parser.add_argument("output", type=Path, help="JSON results path")
    parser.add_argument(
        "--reader",
        choices=("tesseract", "paddleocr-vl", "glm-ocr", "glm-ocr-direct"),
        default="tesseract",
    )
    parser.add_argument(
        "--model",
        choices=sorted(IMAGE_REPAIR_MODELS),
        default="qwen/qwen3.8-flash",
    )
    parser.add_argument("--provider", help="Exact OpenRouter provider slug")
    parser.add_argument(
        "--verifier-model",
        choices=sorted(IMAGE_REPAIR_MODELS),
        help="Independent verifier model (defaults to a different image model)",
    )
    parser.add_argument(
        "--verifier-provider",
        help="Exact OpenRouter provider slug for the verifier",
    )
    parser.add_argument("--subset", help="Run only this public dataset subset")
    parser.add_argument("--limit-per-subset", type=_positive_int)
    parser.add_argument("--max-tokens", type=_max_tokens, default=DEFAULT_MAX_TOKENS)
    parser.add_argument("--language", default="eng")
    parser.add_argument("--tesseract", default="tesseract")
    parser.add_argument("--backend", default="native")
    parser.add_argument("--device")
    parser.add_argument("--ocr-api-host", help="GLM-OCR SDK recognition server host")
    parser.add_argument(
        "--ocr-api-port",
        type=_positive_int,
        help="GLM-OCR SDK recognition server port",
    )
    parser.add_argument("--layout-device", help="GLM-OCR SDK layout model device")
    parser.add_argument(
        "--max-new-tokens",
        type=_positive_int,
        default=8192,
        help="Maximum tokens generated by the direct GLM-OCR model",
    )
    parser.add_argument(
        "--use-doc-orientation-classify",
        action=argparse.BooleanOptionalAction,
        default=None,
    )
    parser.add_argument(
        "--use-doc-unwarping",
        action=argparse.BooleanOptionalAction,
        default=None,
    )
    args = parser.parse_args(argv)

    try:
        reader = _reader_from_args(args)
        payload = run_benchmark(
            args.dataset,
            args.root,
            reader,
            args.model,
            provider_slug=args.provider,
            verifier_model=args.verifier_model,
            verifier_provider_slug=args.verifier_provider,
            subset=args.subset,
            limit_per_subset=args.limit_per_subset,
            max_tokens=args.max_tokens,
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(
            json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
    except (OSError, ValueError) as error:
        parser.error(str(error))
    return 0


def run_benchmark(
    dataset: str,
    root: Path,
    reader: LocalReader,
    model: str,
    *,
    provider_slug: str | None = None,
    verifier_model: str | None = None,
    verifier_provider_slug: str | None = None,
    subset: str | None = None,
    limit_per_subset: int | None = None,
    max_tokens: int = DEFAULT_MAX_TOKENS,
    repair_call: RepairCall | None = None,
    verifier_call: RepairCall | None = None,
) -> dict[str, object]:
    if verifier_model is None:
        verifier_model = _default_verifier_model(model)
    _validate_options(
        model,
        provider_slug,
        verifier_model,
        verifier_provider_slug,
        limit_per_subset,
        max_tokens,
    )
    cases = discover_cases(dataset, root)
    if subset is not None:
        cases = [case for case in cases if case.subset == subset]
    if limit_per_subset is not None:
        cases = _limit_cases(cases, limit_per_subset)
    if not cases:
        selection = f" subset {subset!r}" if subset is not None else ""
        raise ValueError(f"No evaluation cases found in {root}{selection}")

    hosted_repair = repair_call or _hosted_repair(model, provider_slug, max_tokens)
    hosted_verifier = verifier_call or _hosted_repair(
        verifier_model,
        verifier_provider_slug,
        max_tokens,
    )
    records = [
        _evaluate_case(case, root, reader, hosted_repair, hosted_verifier)
        for case in cases
    ]
    subsets = {
        name: _comparison_summary(
            [record for record in records if record["subset"] == name]
        )
        for name in sorted({case.subset for case in cases})
    }
    return {
        "dataset": dataset,
        "dataset_root": str(root.resolve()),
        "reader": reader.name,
        "run_config": {
            **reader_config(reader),
            "repair_model": model,
            "provider_slug": provider_slug,
            "verifier_model": verifier_model,
            "verifier_provider_slug": verifier_provider_slug,
            "selected_subset": subset,
            "limit_per_subset": limit_per_subset,
            "max_tokens": max_tokens,
            "repair_protocol_version": REPAIR_PROTOCOL_VERSION,
        },
        "repair_model": model,
        "provider_slug": provider_slug,
        "verifier_model": verifier_model,
        "verifier_provider_slug": verifier_provider_slug,
        "repair_protocol_version": REPAIR_PROTOCOL_VERSION,
        "selected_subset": subset,
        "limit_per_subset": limit_per_subset,
        "max_tokens": max_tokens,
        "normalization": NORMALIZATION,
        "summary": _comparison_summary(records),
        "subsets": subsets,
        "cases": records,
    }


def _evaluate_case(
    case: BenchmarkCase,
    root: Path,
    reader: LocalReader,
    hosted_repair: RepairCall,
    hosted_verifier: RepairCall,
) -> dict[str, object]:
    total_started = time.perf_counter()
    local_started = time.perf_counter()
    local_document = process_document(case.image_path, reader)
    local_wall_latency_ms = round((time.perf_counter() - local_started) * 1000, 3)
    local_structured = "\n\n".join(page.text.value for page in local_document.pages)
    local_prediction = _transcription_text(local_structured)
    local_failures = [failure.__dict__ for failure in local_document.failures]
    local_status, local_failures = _outcome(
        local_document.status, local_prediction, local_failures
    )

    primary_calls = 0
    verifier_calls = 0

    def counted_repair(image_path: Path, prompt: str, schema: Mapping[str, Any]) -> Any:
        nonlocal primary_calls
        primary_calls += 1
        return hosted_repair(image_path, prompt, schema)

    def counted_verifier(
        image_path: Path, prompt: str, schema: Mapping[str, Any]
    ) -> Any:
        nonlocal verifier_calls
        verifier_calls += 1
        return hosted_verifier(image_path, prompt, schema)

    repaired_document, repair_records = repair_risky_regions(
        local_document,
        {1: case.image_path},
        counted_repair,
        counted_verifier,
    )
    repaired_structured = "\n\n".join(
        page.text.value for page in repaired_document.pages
    )
    repaired_prediction = _transcription_text(repaired_structured)
    repair_failures = [
        {
            "stage": "repair",
            "code": str(record["reason"]),
            "message": _repair_failure_message(record),
        }
        for record in repair_records
        if record["status"] != "accepted"
    ]
    repaired_failures = [
        *(failure.__dict__ for failure in repaired_document.failures),
        *repair_failures,
    ]
    repaired_status, repaired_failures = _outcome(
        repaired_document.status,
        repaired_prediction,
        repaired_failures,
    )
    total_wall_latency_ms = round((time.perf_counter() - total_started) * 1000, 3)

    # References are used only after local routing and visual repair are complete.
    return {
        "id": case.id,
        "cluster_id": case.cluster_id,
        "subset": case.subset,
        "image": _relative_path(case.image_path, root),
        "reference": case.reference,
        "local": {
            "prediction": local_prediction,
            "structured_prediction": local_structured,
            "status": local_status,
            "metrics": _score(local_prediction, case.reference),
            "failures": local_failures,
        },
        "repaired": {
            "prediction": repaired_prediction,
            "structured_prediction": repaired_structured,
            "status": repaired_status,
            "metrics": _score(repaired_prediction, case.reference),
            "failures": repaired_failures,
        },
        "repair": {
            "calls": primary_calls + verifier_calls,
            "primary_calls": primary_calls,
            "verifier_calls": verifier_calls,
            "accepted": sum(
                record["status"] == "accepted" for record in repair_records
            ),
            "abstained": sum(
                record["status"] != "accepted" for record in repair_records
            ),
            "reported_cost": round(
                sum(
                    float(record["reported_cost"])
                    for record in repair_records
                    if isinstance(record.get("reported_cost"), (int, float))
                    and not isinstance(record.get("reported_cost"), bool)
                ),
                10,
            ),
            "unreported_cost_calls": _unreported_cost_calls(
                repair_records,
                primary_calls + verifier_calls,
            ),
            "records": repair_records,
        },
        "local_wall_latency_ms": local_wall_latency_ms,
        "wall_latency_ms": total_wall_latency_ms,
    }


def _comparison_summary(records: list[dict[str, object]]) -> dict[str, object]:
    return {
        "local": _summarize(
            _variant_records(records, "local", "local_wall_latency_ms")
        ),
        "repaired": _summarize(
            _variant_records(records, "repaired", "wall_latency_ms")
        ),
        "repair_calls": sum(int(record["repair"]["calls"]) for record in records),  # type: ignore[index]
        "reported_repair_cost": round(
            sum(
                float(record["repair"]["reported_cost"])  # type: ignore[index]
                for record in records
            ),
            10,
        ),
        "unreported_cost_calls": sum(
            int(record["repair"]["unreported_cost_calls"])  # type: ignore[index]
            for record in records
        ),
        "wall_latency_ms": round(
            sum(float(record["wall_latency_ms"]) for record in records), 3
        ),
    }


def _variant_records(
    records: list[dict[str, object]], variant: str, latency_field: str
) -> list[dict[str, object]]:
    return [
        {
            "prediction": record[variant]["prediction"],  # type: ignore[index]
            "status": record[variant]["status"],  # type: ignore[index]
            "metrics": record[variant]["metrics"],  # type: ignore[index]
            "failures": record[variant]["failures"],  # type: ignore[index]
            "latency_ms": record[latency_field],
        }
        for record in records
    ]


def _unreported_cost_calls(records: list[dict[str, Any]], total_calls: int) -> int:
    reported_calls = 0
    for record in records:
        for role in ("primary", "verifier"):
            metadata = record.get(role)
            if not isinstance(metadata, Mapping):
                continue
            cost = metadata.get("cost")
            if isinstance(cost, (int, float)) and not isinstance(cost, bool):
                reported_calls += 1
    return total_calls - reported_calls


def _outcome(
    status: str,
    prediction: str,
    failures: list[dict[str, object]],
) -> tuple[str, list[dict[str, object]]]:
    if not prediction.strip() and not any(
        failure.get("code") == "empty_prediction" for failure in failures
    ):
        failures.append(
            {
                "stage": "benchmark",
                "code": "empty_prediction",
                "message": "The pipeline returned no visible text",
            }
        )
    if not prediction.strip():
        return "failed", failures
    if failures or status != "success":
        return "partial", failures
    return "success", failures


def _hosted_repair(
    model: str,
    provider_slug: str | None,
    max_tokens: int,
) -> RepairCall:
    def call(image_path: Path, prompt: str, schema: Mapping[str, Any]) -> Any:
        return repair_image(
            image_path,
            prompt,
            schema,
            model=model,
            provider_slug=provider_slug,
            max_tokens=max_tokens,
        )

    return call


def _reader_from_args(args: argparse.Namespace) -> LocalReader:
    if args.reader == "tesseract":
        return TesseractReader(language=args.language, executable=args.tesseract)
    if args.reader == "paddleocr-vl":
        return PaddleOCRVLReader(
            backend=args.backend,
            device=args.device,
            use_doc_orientation_classify=args.use_doc_orientation_classify,
            use_doc_unwarping=args.use_doc_unwarping,
        )
    if args.reader == "glm-ocr":
        return GLMOCRReader(
            ocr_api_host=args.ocr_api_host,
            ocr_api_port=args.ocr_api_port,
            layout_device=args.layout_device,
        )
    return GLMOCRDirectReader(max_new_tokens=args.max_new_tokens)


def _validate_options(
    model: str,
    provider_slug: str | None,
    verifier_model: str,
    verifier_provider_slug: str | None,
    limit_per_subset: int | None,
    max_tokens: int,
) -> None:
    if model not in IMAGE_REPAIR_MODELS:
        raise ValueError(f"Unsupported repair model: {model}")
    if verifier_model not in IMAGE_REPAIR_MODELS:
        raise ValueError(f"Unsupported verifier model: {verifier_model}")
    _validate_provider_slug(provider_slug, "Provider")
    _validate_provider_slug(verifier_provider_slug, "Verifier provider")
    if model == verifier_model:
        raise ValueError("Verifier must use a different model")
    if limit_per_subset is not None and limit_per_subset < 1:
        raise ValueError("Limit per subset must be positive")
    if isinstance(max_tokens, bool) or not 1 <= max_tokens <= MAX_TOKENS:
        raise ValueError(f"Max tokens must be between 1 and {MAX_TOKENS}")


def _validate_provider_slug(value: str | None, name: str) -> None:
    if value is not None and (not value or value != value.strip()):
        raise ValueError(f"{name} slug must be a non-empty trimmed string")


def _default_verifier_model(model: str) -> str:
    alternatives = sorted(IMAGE_REPAIR_MODELS - {model})
    if not alternatives:
        raise ValueError("An explicit verifier model is required")
    return alternatives[0]


def _repair_failure_message(record: Mapping[str, Any]) -> str:
    for field in ("primary_error", "verifier_error"):
        error = record.get(field)
        if isinstance(error, Mapping) and isinstance(error.get("message"), str):
            return str(error["message"])
    return f"Repair abstained: {record['reason']}"


def _max_tokens(value: str) -> int:
    number = int(value)
    if not 1 <= number <= MAX_TOKENS:
        raise argparse.ArgumentTypeError(
            f"max tokens must be between 1 and {MAX_TOKENS}"
        )
    return number


if __name__ == "__main__":
    raise SystemExit(main())
