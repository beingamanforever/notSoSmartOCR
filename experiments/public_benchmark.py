def run_benchmark(
    dataset: str,
    root: Path,
    workers: int,
    reader: LocalReader,
    *,
    limit_per_subset: int | None = None,
    selected_subsets: set[str] | None = None,
    pdf_dpi: int = 300,
    clinocr_role: str = "eval",
    cuda_monitor: object | None = None,
) -> dict[str, object]:
    cases = discover_cases(dataset, root, clinocr_role=clinocr_role)
    if selected_subsets:
        available_subsets = {case.subset for case in cases}
        unknown_subsets = selected_subsets - available_subsets
        if unknown_subsets:
            raise ValueError(f"Unknown subsets: {sorted(unknown_subsets)}")
        cases = [case for case in cases if case.subset in selected_subsets]
    if limit_per_subset is not None:
        cases = _limit_cases(cases, limit_per_subset)
    if not cases:
        raise ValueError(f"No evaluation cases found in {root}")

    monitor = cuda_monitor
    if monitor is None and not isinstance(reader, TesseractReader):
        monitor = CudaMonitor()
    if monitor is not None:
        getattr(monitor, "begin")()
    started = time.perf_counter()
    try:
        with ThreadPoolExecutor(max_workers=workers) as executor:
            records = list(
                executor.map(
                    lambda case: _evaluate_case(case, root, reader, pdf_dpi), cases
                )
            )
    finally:
        peak_cuda_bytes = getattr(monitor, "finish")() if monitor is not None else None
    wall_latency_ms = (time.perf_counter() - started) * 1000

    subsets = {
        subset: _summarize([record for record in records if record["subset"] == subset])
        for subset in sorted({case.subset for case in cases})
    }
    summary = _summarize(records, wall_latency_ms=wall_latency_ms)
    summary["gpu_memory"] = {
        "basis": "pytorch_cuda_peak_allocated_bytes",
        "peak_bytes": peak_cuda_bytes,
        "available": peak_cuda_bytes is not None,
        "scope": "whole benchmark process",
    }
    return {
        "dataset": dataset,
        "dataset_revision": DATASET_REVISIONS[dataset],
        "dataset_root": str(root.resolve()),
        "case_ids": [case.id for case in cases],
        "reader": reader.name,
        "run_config": _run_config(
            reader,
            workers,
            selected_subsets,
            limit_per_subset,
            pdf_dpi,
            clinocr_role if dataset == "clinocr" else None,
        ),
        "normalization": NORMALIZATION,
        "summary": summary,
        "subsets": subsets,
        "cases": records,
    }


def discover_cases(
    dataset: str,
    root: Path,
    *,
    clinocr_role: str = "eval",
) -> list[BenchmarkCase]:
    if dataset == "clinocr":
        return _discover_clinocr(root, clinocr_role)
    if dataset == "funsd":
        return _discover_funsd(root)
    raise ValueError(f"Unsupported dataset: {dataset}")


def _discover_clinocr(root: Path, role: str = "eval") -> list[BenchmarkCase]:
    if role not in {"eval", "exemplar"}:
        raise ValueError(f"Unsupported ClinOCR role: {role}")
    lookup_path = root / "oneshot_lookup.csv"
    if not lookup_path.is_file():
        raise ValueError(f"ClinOCR lookup not found: {lookup_path}")

    cases: list[BenchmarkCase] = []
    with lookup_path.open(encoding="utf-8-sig", newline="") as lookup_file:
        rows = csv.DictReader(lookup_file)
        required = {"subset", "template", "sample", "role"}
        if not rows.fieldnames or not required.issubset(rows.fieldnames):
            raise ValueError(f"ClinOCR lookup has invalid columns: {lookup_path}")

        for row in rows:
            if row["role"].strip().casefold() != role:
                continue
            subset = row["subset"].strip()
            template = row["template"].strip()
            sample = row["sample"].strip()
            stem = f"template_{template}_sample_{sample}_{subset}"
            reference_path = root / "ground_truth" / subset / f"{stem}.txt"
            if not reference_path.is_file():
                raise ValueError(f"ClinOCR reference not found: {reference_path}")
            image_path = _find_image(root / "scans" / subset, stem, ".jpg")
            cases.append(
                BenchmarkCase(
                    id=f"{subset}/{stem}",
                    cluster_id=template,
                    subset=subset,
                    image_path=image_path,
                    reference=reference_path.read_text(encoding="utf-8-sig"),
                )
            )
    return sorted(cases, key=lambda case: case.id)


def _discover_funsd(root: Path) -> list[BenchmarkCase]:
    annotations_dir = root / "testing_data" / "annotations"
    images_dir = root / "testing_data" / "images"
    if not annotations_dir.is_dir():
        raise ValueError(f"FUNSD test annotations not found: {annotations_dir}")

    cases = []
    for annotation_path in sorted(annotations_dir.glob("*.json")):
        annotation = json.loads(annotation_path.read_text(encoding="utf-8-sig"))
        cases.append(
            BenchmarkCase(
                id=f"test/{annotation_path.stem}",
                cluster_id=f"test/{annotation_path.stem}",
                subset="test",
                image_path=_find_image(images_dir, annotation_path.stem, ".png"),
                reference=_funsd_reference(annotation, annotation_path),
            )
        )
    return cases


def _evaluate_case(
    case: BenchmarkCase,
    root: Path,
    reader: LocalReader,
    pdf_dpi: int,
) -> dict[str, object]:
    started = time.perf_counter()
    result = process_document(case.image_path, reader, pdf_dpi=pdf_dpi)
    latency_ms = (time.perf_counter() - started) * 1000
    structured_prediction = "\n\n".join(page.text.value for page in result.pages)
    prediction = _transcription_text(structured_prediction)
    metrics = _score(prediction, case.reference)
    return {
        "id": case.id,
        "cluster_id": case.cluster_id,
        "subset": case.subset,
        "image": _relative_path(case.image_path, root),
        "prediction": prediction,
        "structured_prediction": structured_prediction,
        "reference": case.reference,
        "status": result.status,
        "metrics": metrics,
        "failures": [failure.__dict__ for failure in result.failures],
        "latency_ms": round(latency_ms, 3),
    }


def _score(prediction: str, reference: str) -> dict[str, dict[str, float | int]]:
    normalized_prediction = _normalize(prediction)
    normalized_reference = _normalize(reference)
    prediction_words = normalized_prediction.split()
    reference_words = normalized_reference.split()
    character_counts = edit_counts(normalized_prediction, normalized_reference)
    word_counts = edit_counts(prediction_words, reference_words)
    reference_characters = len(normalized_reference)
    longer_text_characters = max(
        len(normalized_prediction),
        reference_characters,
    )
    return {
        "cer": _case_metric(character_counts.edits, reference_characters),
        "wer": _case_metric(word_counts.edits, len(reference_words)),
        "normalized_edit_distance": {
            "edits": character_counts.edits,
            "longer_text_characters": longer_text_characters,
            "rate": round(
                normalized_edit_distance(
                    normalized_prediction,
                    normalized_reference,
                ),
                6,
            ),
        },
        "character_edit_counts": _edit_count_payload(character_counts),
        "word_edit_counts": _edit_count_payload(word_counts),
        "missed_text_rate": _case_reference_character_rate(
            character_counts.deletions,
            reference_characters,
            "character_deletions",
        ),
        "hallucinated_text_rate": _case_reference_character_rate(
            character_counts.insertions,
            reference_characters,
            "character_insertions",
        ),
    }


def _summarize(
    records: list[dict[str, object]],
    *,
    wall_latency_ms: float | None = None,
    latency_field: str = "latency_ms",
    latency_basis: str = "per_case_wall_latency_ms",
) -> dict[str, object]:
    case_count = len(records)
    covered_count = sum(
        bool(_normalize(str(record["prediction"]))) for record in records
    )
    status_counts = Counter(str(record["status"]) for record in records)
    failed_count = case_count - status_counts.get("success", 0)
    abstained_count = sum(
        record["status"] == "success" and not _normalize(str(record["prediction"]))
        for record in records
    )
    failure_codes = Counter(
        str(failure["code"])
        for record in records
        for failure in record["failures"]  # type: ignore[union-attr]
    )
    latencies = [
        float(record[latency_field])
        for record in records
        if isinstance(record.get(latency_field), (int, float))
        and not isinstance(record.get(latency_field), bool)
    ]

    summary: dict[str, object] = {
        "cases": case_count,
        "covered_cases": covered_count,
        "coverage": _ratio(covered_count, case_count),
        "failed_cases": failed_count,
        "failure_rate": _ratio(failed_count, case_count),
        "abstained_cases": abstained_count,
        "abstention_rate": _ratio(abstained_count, case_count),
        "pipeline_failures": sum(failure_codes.values()),
        "status_counts": dict(sorted(status_counts.items())),
        "failure_codes": dict(sorted(failure_codes.items())),
        "cer": _aggregate_metric(records, "cer"),
        "wer": _aggregate_metric(records, "wer"),
        "normalized_edit_distance": _aggregate_normalized_edit_distance(records),
        "character_edit_counts": _aggregate_edit_counts(
            records, "character_edit_counts"
        ),
        "word_edit_counts": _aggregate_edit_counts(records, "word_edit_counts"),
        "missed_text_rate": _aggregate_reference_character_rate(
            records,
            "missed_text_rate",
            "character_deletions",
        ),
        "hallucinated_text_rate": _aggregate_reference_character_rate(
            records,
            "hallucinated_text_rate",
            "character_insertions",
        ),
        "latency_ms": {
            "basis": latency_basis,
            **_latency_summary(latencies, case_count),
        },
    }
    if any("cost" in record for record in records):
        reported_costs = [
            float(record["cost"])
            for record in records
            if isinstance(record.get("cost"), (int, float))
            and not isinstance(record.get("cost"), bool)
        ]
        reported_cost = round(sum(reported_costs), 10) if reported_costs else None
        unreported_cost_cases = case_count - len(reported_costs)
        summary.update(
            {
                "reported_cost": reported_cost,
                "cost_per_page": (
                    round(reported_cost / case_count, 10)
                    if reported_cost is not None and unreported_cost_cases == 0
                    else None
                ),
                "cost_per_reported_page": (
                    round(reported_cost / len(reported_costs), 10)
                    if reported_cost is not None
                    else None
                ),
                "unreported_cost_cases": unreported_cost_cases,
            }
        )
    if wall_latency_ms is not None:
        summary.update(
            {
                "wall_latency_ms": round(wall_latency_ms, 3),
                "pages_per_second": (
                    round(case_count / (wall_latency_ms / 1000), 6)
                    if wall_latency_ms > 0
                    else 0.0
                ),
            }
        )
    return summary


def _latency_summary(
    latencies: list[float], attempted_cases: int
) -> dict[str, float | int | None]:
    return {
        "observed_cases": len(latencies),
        "missing_cases": attempted_cases - len(latencies),
        "p50": round(_percentile(latencies, 0.50), 3) if latencies else None,
        "p95": round(_percentile(latencies, 0.95), 3) if latencies else None,
    }


def _aggregate_metric(
    records: list[dict[str, object]], name: str
) -> dict[str, float | int]:
    case_metrics = [record["metrics"][name] for record in records]  # type: ignore[index]
    edits = sum(int(metric["edits"]) for metric in case_metrics)
    reference_units = sum(int(metric["reference_units"]) for metric in case_metrics)
    return {
        "case_mean": round(
            sum(float(metric["rate"]) for metric in case_metrics) / len(case_metrics),
            6,
        ),
        "micro": round(_ratio(edits, reference_units), 6),
        "edits": edits,
        "reference_units": reference_units,
    }


def _case_metric(edits: int, reference_units: int) -> dict[str, float | int]:
    return {
        "edits": edits,
        "reference_units": reference_units,
        "rate": round(_ratio(edits, reference_units), 6),
    }


def _edit_count_payload(counts: EditCounts) -> dict[str, int]:
    return {
        "substitutions": counts.substitutions,
        "insertions": counts.insertions,
        "deletions": counts.deletions,
    }


def _case_reference_character_rate(
    numerator: int,
    reference_characters: int,
    numerator_name: str,
) -> dict[str, float | int]:
    return {
        numerator_name: numerator,
        "normalized_reference_characters": reference_characters,
        "rate": round(_ratio(numerator, reference_characters), 6),
    }


def _aggregate_normalized_edit_distance(
    records: list[dict[str, object]],
) -> dict[str, float | int]:
    metrics = [
        record["metrics"]["normalized_edit_distance"]  # type: ignore[index]
        for record in records
    ]
    edits = sum(int(metric["edits"]) for metric in metrics)
    longer_text_characters = sum(
        int(metric["longer_text_characters"]) for metric in metrics
    )
    return {
        "case_mean": round(
            sum(float(metric["rate"]) for metric in metrics) / len(metrics),
            6,
        ),
        "micro": round(_ratio(edits, longer_text_characters), 6),
        "edits": edits,
        "longer_text_characters": longer_text_characters,
    }


def _aggregate_edit_counts(
    records: list[dict[str, object]],
    name: str,
) -> dict[str, int]:
    metrics = [record["metrics"][name] for record in records]  # type: ignore[index]
    return {
        operation: sum(int(metric[operation]) for metric in metrics)
        for operation in ("substitutions", "insertions", "deletions")
    }


def _aggregate_reference_character_rate(
    records: list[dict[str, object]],
    name: str,
    numerator_name: str,
) -> dict[str, float | int]:
    metrics = [record["metrics"][name] for record in records]  # type: ignore[index]
    numerator = sum(int(metric[numerator_name]) for metric in metrics)
    reference_characters = sum(
        int(metric["normalized_reference_characters"]) for metric in metrics
    )
    return {
        "case_mean": round(
            sum(float(metric["rate"]) for metric in metrics) / len(metrics),
            6,
        ),
        "micro": round(_ratio(numerator, reference_characters), 6),
        numerator_name: numerator,
        "normalized_reference_characters": reference_characters,
    }


def _funsd_reference(annotation: object, path: Path) -> str:
    if not isinstance(annotation, dict) or not isinstance(annotation.get("form"), list):
        raise ValueError(f"Invalid FUNSD annotation: {path}")

    words: list[tuple[int, int, str]] = []
    for item in annotation["form"]:
        if not isinstance(item, dict) or not isinstance(item.get("words"), list):
            raise ValueError(f"Invalid FUNSD annotation item: {path}")
        for word in item["words"]:
            if not isinstance(word, dict) or not isinstance(word.get("box"), list):
                raise ValueError(f"Invalid FUNSD word: {path}")
            text = str(word.get("text", "")).strip()
            box = word["box"]
            if text and len(box) >= 2:
                words.append((int(box[1]), int(box[0]), text))
    words.sort()
    return " ".join(text for _, _, text in words)


def _find_image(directory: Path, stem: str, default_suffix: str) -> Path:
    matches = [
        path
        for path in directory.glob(f"{stem}.*")
        if path.is_file() and path.suffix.casefold() in IMAGE_SUFFIXES
    ]
    if len(matches) > 1:
        raise ValueError(f"Multiple images found for {stem}: {directory}")
    return matches[0] if matches else directory / f"{stem}{default_suffix}"


def _relative_path(path: Path, root: Path) -> str:
    try:
        return str(path.relative_to(root))
    except ValueError:
        return str(path)


def _normalize(text: str) -> str:
    return " ".join(unicodedata.normalize("NFKC", text).casefold().split())


def _transcription_text(text: str) -> str:
    if not re.search(r"</?(?:table|thead|tbody|tfoot|tr|td|th)\b", text, re.I):
        return text
    parser = _TextExtractor()
    parser.feed(text)
    parser.close()
    return " ".join(parser.parts)


class _TextExtractor(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.parts: list[str] = []

    def handle_data(self, data: str) -> None:
        if data.strip():
            self.parts.append(data.strip())


def _ratio(numerator: int, denominator: int) -> float:
    if denominator == 0:
        return 0.0 if numerator == 0 else float(numerator)
    return numerator / denominator


def _percentile(values: list[float], percentile: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    position = (len(ordered) - 1) * percentile
    lower = math.floor(position)
    upper = math.ceil(position)
    if lower == upper:
        return ordered[lower]
    return ordered[lower] + (ordered[upper] - ordered[lower]) * (position - lower)


def _worker_count(value: str) -> int:
    workers = int(value)
    if not 1 <= workers <= MAX_WORKERS:
        raise argparse.ArgumentTypeError(f"workers must be between 1 and {MAX_WORKERS}")
    return workers


def _positive_int(value: str) -> int:
    number = int(value)
    if number < 1:
        raise argparse.ArgumentTypeError("value must be positive")
    return number


def _tesseract_psm(value: str) -> int:
    number = int(value)
    if not 0 <= number <= 13:
        raise argparse.ArgumentTypeError("value must be from 0 to 13")
    return number


def _tesseract_thresholding(value: str) -> int:
    number = int(value)
    if number not in {0, 1, 2}:
        raise argparse.ArgumentTypeError("value must be 0, 1, or 2")
    return number


def _ocr_api_host(value: str) -> str:
    try:
        host = _validate_ocr_api_host(value)
    except ValueError as error:
        raise argparse.ArgumentTypeError(str(error)) from None
    if host is None:
        raise argparse.ArgumentTypeError(OCR_API_HOST_ERROR)
    return host


def _validate_ocr_api_host(value: str | None) -> str | None:
    if value is None:
        return None
    if not value or value != value.strip() or not value.isascii() or "%" in value:
        raise ValueError(OCR_API_HOST_ERROR)
    try:
        ipaddress.ip_address(value)
    except ValueError:
        labels = value.split(".")
        if len(value) > 253 or any(
            HOSTNAME_LABEL.fullmatch(label) is None for label in labels
        ):
            raise ValueError(OCR_API_HOST_ERROR) from None
    return value


def _reader_from_args(args: argparse.Namespace) -> LocalReader:
    if args.reader == "tesseract":
        return TesseractReader(
            language=args.language,
            executable=args.tesseract,
            page_segmentation_mode=args.tesseract_psm,
            thresholding_method=args.tesseract_thresholding,
        )
    if args.reader == "paddleocr-vl":
        return PaddleOCRVLReader(
            backend=args.backend,
            device=args.device,
            use_doc_orientation_classify=args.use_doc_orientation_classify,
            use_doc_unwarping=args.use_doc_unwarping,
        )
    if args.reader == "glm-ocr":
        return GLMOCRReader(
            ocr_api_host=_validate_ocr_api_host(args.ocr_api_host),
            ocr_api_port=args.ocr_api_port,
            layout_device=args.layout_device,
        )
    if args.reader == "glm-ocr-direct":
        return GLMOCRDirectReader(max_new_tokens=args.max_new_tokens)
    if args.reader == "granite-docling":
        return GraniteDoclingReader(
            max_new_tokens=args.max_new_tokens,
            output_format=args.granite_output_format,
        )
    return NemotronOCRV2Reader(
        language=args.nemotron_language,
        merge_level=args.nemotron_merge_level,
    )


def _run_config(
    reader: LocalReader,
    workers: int,
    selected_subsets: set[str] | None,
    limit_per_subset: int | None,
    pdf_dpi: int,
    clinocr_role: str | None = None,
) -> dict[str, object]:
    return {
        **reader_config(reader),
        "workers": workers,
        "selected_subsets": sorted(selected_subsets) if selected_subsets else None,
        "limit_per_subset": limit_per_subset,
        "pdf_dpi": pdf_dpi,
        "clinocr_role": clinocr_role,
    }


def reader_config(reader: LocalReader) -> dict[str, object]:
    """Serialize behavior-affecting reader options without credentials."""
    reader_options: dict[str, object] = {}
    if isinstance(reader, TesseractReader):
        reader_options = {
            "language": reader.language,
            "executable": reader.executable,
            "timeout_seconds": reader.timeout_seconds,
            "page_segmentation_mode": reader.page_segmentation_mode,
            "thresholding_method": reader.thresholding_method,
        }
    elif isinstance(reader, PaddleOCRVLReader):
        reader_options = {
            "pipeline_version": reader.pipeline_version,
            "backend": reader.backend,
            "device": reader.device,
            "use_doc_orientation_classify": reader.use_doc_orientation_classify,
            "use_doc_unwarping": reader.use_doc_unwarping,
        }
    elif isinstance(reader, GLMOCRReader):
        reader_options = {
            "ocr_api_host": _validate_ocr_api_host(reader.ocr_api_host),
            "ocr_api_port": reader.ocr_api_port,
            "layout_device": reader.layout_device,
        }
    elif isinstance(reader, GLMOCRDirectReader):
        reader_options = {
            "model_name": reader.model_name,
            "max_new_tokens": reader.max_new_tokens,
        }
    elif isinstance(reader, GraniteDoclingReader):
        reader_options = {
            "model_name": reader.model_name,
            "max_new_tokens": reader.max_new_tokens,
            "output_format": reader.output_format,
        }
    elif isinstance(reader, NemotronOCRV2Reader):
        reader_options = {
            "language": reader.language,
            "merge_level": reader.merge_level,
        }
    return {
        "reader": reader.name,
        "reader_options": reader_options,
    }


def _limit_cases(
    cases: list[BenchmarkCase], limit_per_subset: int
) -> list[BenchmarkCase]:
    counts: Counter[str] = Counter()
    selected = []
    for case in cases:
        if counts[case.subset] >= limit_per_subset:
            continue
        selected.append(case)
        counts[case.subset] += 1
    return selected


